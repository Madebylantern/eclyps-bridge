// Regenerates circuits/merkle-nr/src/vectors.nr from circuits/vectors/merkle.json.
// Usage: node circuits/scripts/gen-noir-vectors.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("..", import.meta.url);
const v = JSON.parse(readFileSync(new URL("vectors/merkle.json", dir), "utf8"));
const arr = (xs) => `[\n    ${xs.join(",\n    ")},\n]`;
const g = (name, ty, val) => `pub global ${name}: ${ty} = ${val};\n`;

let out = "// Generated by circuits/scripts/gen-noir-vectors.mjs from circuits/vectors/merkle.json. Do not edit.\n\n";
out += g("PAIRS_A", `[Field; ${v.pairs.length}]`, arr(v.pairs.map((p) => p.a)));
out += g("PAIRS_B", `[Field; ${v.pairs.length}]`, arr(v.pairs.map((p) => p.b)));
out += g("PAIRS_OUT", `[Field; ${v.pairs.length}]`, arr(v.pairs.map((p) => p.out)));
out += g("NOTE_KEYS", "[Field; 16]", arr(v.notes.map((n) => n.nullifier_key)));
out += g("NOTE_SECRETS", "[Field; 16]", arr(v.notes.map((n) => n.secret)));
out += g("NOTE_COMMITMENTS", "[Field; 16]", arr(v.notes.map((n) => n.commitment)));
out += g("ROOT_DEPTH4_16", "Field", v.root_depth4_16_leaves);
out += g("ROOT_BATCH_16", "Field", v.root_batch_depth_16_leaves);
out += g("ROOT_BATCH_FIRST_11", "Field", v.root_batch_depth_first_11_leaves);
out += g("ZERO_HASHES", `[Field; ${v.zero_hashes.length}]`, arr(v.zero_hashes));
const ps = v.paths_batch_depth;
out += g("PATH_INDICES", `[u32; ${ps.length}]`, `[${ps.map((p) => p.index).join(", ")}]`);
out += g(
  "PATH_SIBLINGS",
  `[[Field; ${v.batch_depth}]; ${ps.length}]`,
  `[\n    ${ps.map((p) => `[${p.siblings.join(", ")}]`).join(",\n    ")},\n]`,
);
writeFileSync(new URL("merkle-nr/src/vectors.nr", dir), out);

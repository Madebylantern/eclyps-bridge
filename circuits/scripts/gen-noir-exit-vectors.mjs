// Regenerates aztec/claim_test/src/exit_vectors.nr from circuits/vectors/exit.json,
// circuits/vectors/exit-ethereum.json and the exit batch the gateway received and paid in LiteSVM
// (sdk/test/fixtures/exit-claim.json), for the claim contract's TXE tests.
// Usage: node circuits/scripts/gen-noir-exit-vectors.mjs
import { readFileSync, writeFileSync } from "node:fs";

const dir = new URL("..", import.meta.url);
const read = (f) => JSON.parse(readFileSync(new URL(`vectors/${f}`, dir), "utf8"));
const exit = read("exit.json").vectors;
const eth = read("exit-ethereum.json");
const fixture = JSON.parse(readFileSync(new URL("../sdk/test/fixtures/exit-claim.json", dir), "utf8"));
if (fixture.root !== exit[0].root || String(fixture.exitEpochId) !== exit[0].exitEpochId) {
  throw new Error("exit.json vector 0 is no longer the gateway's fixture batch");
}
const arr = (xs) => `[\n    ${xs.join(",\n    ")},\n]`;
const g = (name, ty, xs) => `pub global ${name}: [${ty}; ${xs.length}] = ${arr(xs)};\n`;

let out =
  "// Generated by circuits/scripts/gen-noir-exit-vectors.mjs from circuits/vectors/exit.json,\n" +
  "// circuits/vectors/exit-ethereum.json and sdk/test/fixtures/exit-claim.json. Do not edit.\n\n";
out += g("EXIT_DENOMINATION", "u128", exit.map((v) => v.denomination));
out += g("EXIT_EPOCH_ID", "u64", exit.map((v) => v.exitEpochId));
out += g("EXIT_COUNT", "u32", exit.map((v) => String(v.count)));
out += g("EXIT_ROOT", "Field", exit.map((v) => v.root));
out += g("EXIT_CONTENT", "Field", exit.map((v) => v.content));
out += "// The leaves of exit.json vector 0, in order: the batch the gateway paid in LiteSVM.\n";
out += g("FIXTURE_LEAVES", "Field", fixture.exits.map((e) => e.leaf));
out += `pub global ETH_TAG: Field = ${eth.tag};\n`;
out += g("ETH_RECIPIENT", "Field", eth.vectors.map((v) => v.recipient));
out += g("ETH_SECRET", "Field", eth.vectors.map((v) => v.exitSecret));
out += g("ETH_DENOMINATION", "u128", eth.vectors.map((v) => v.denomination));
out += g("ETH_COMMITMENT", "Field", eth.vectors.map((v) => v.commitment));
out += g("ETH_CONTENT", "Field", eth.vectors.map((v) => v.content));
writeFileSync(new URL("../aztec/claim_test/src/exit_vectors.nr", dir), out);
